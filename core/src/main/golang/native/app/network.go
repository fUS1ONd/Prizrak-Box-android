package app

import (
	"github.com/metacubex/mihomo/tunnel"
	"github.com/metacubex/mihomo/tunnel/statistic"
)

// NotifyNetworkChanged — явный сигнал «дефолтная сеть системы сменилась» от
// наблюдателя сетей сервисного слоя (см. docs/adr/0001). Внутриядерный монитор
// интерфейса на Android не работает (AutoRoute=false, netlink запрещён),
// поэтому единственный источник сигнала — ConnectivityManager клиента.
// Вся механика реакции (залп, гейт готовности, дебаунс, поколения)
// инкапсулирована в ядре за этим вызовом.
func NotifyNetworkChanged() {
	tunnel.ForceHealthCheckAll()
}

// NotifyTunnelUp — реакция на поднятие туннеля. Два действия, которых ядро
// само по себе не делает:
//
//  1. Разрыв соединений, установленных до включения VPN: VpnService уже
//     открытые сокеты не трогает, и приложения продолжают лить через них
//     мимо туннеля, пока те не отвалятся сами.
//  2. Форс-чек нод: первая волна health-check уходит вместе со стартом ядра —
//     в ещё не поднявшийся туннель — и ложно метит мёртвыми все ноды, включая
//     живые. Группа остаётся «без живых» и льёт в первую по списку до
//     штатного тика. Гейт готовности внутри форс-чека дождётся, пока путь
//     реально начнёт пропускать трафик, и только потом перепроверит.
func NotifyTunnelUp() {
	statistic.DefaultManager.Range(func(c statistic.Tracker) bool {
		_ = c.Close()
		return true
	})
	tunnel.ForceHealthCheckAll()
}
