package app

import (
	"github.com/metacubex/mihomo/tunnel"
)

// ForceHealthCheckAll — нейтральный вход форс-чека для сигналов клиента:
// немедленная перепроверка живости всех нод. Семантика сигнала живёт у
// источников (смена сети у наблюдателя сетей — см. docs/adr/0001, включение
// экрана у модуля усыпления); вся механика реакции (залп, гейт готовности,
// дебаунс, поколения) инкапсулирована в ядре. Внутриядерный монитор
// интерфейса на Android не работает (AutoRoute=false, netlink запрещён),
// поэтому сигналы приходят только отсюда.
func ForceHealthCheckAll() {
	tunnel.ForceHealthCheckAll()
}

// NotifyTunnelUp — реакция на поднятие туннеля: форс-чек нод.
//
// Первая волна health-check уходит вместе со стартом ядра — в ещё не
// поднявшийся туннель — и ложно метит мёртвыми все ноды, включая живые. Группа
// остаётся «без живых» и льёт в первую по списку до штатного тика. Гейт
// готовности внутри форс-чека дождётся, пока путь реально начнёт пропускать
// трафик, и только потом перепроверит.
//
// Разрыва «pre-VPN соединений» здесь нет и быть не может. Сокеты, открытые
// приложениями до включения VPN, живут в чужих процессах — приложению они
// недоступны в принципе. statistic.DefaultManager знает только соединения,
// которые уже идут через ядро; закрывать их — значит рвать живой
// пользовательский трафик (в том числе при переподнятии туннеля поверх
// работающего ядра) и при этом ничего не чинить.
func NotifyTunnelUp() {
	tunnel.ForceHealthCheckAll()
}
